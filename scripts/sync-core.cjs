function relative(fromFile, toFile) {
  let result = path.posix.relative(path.posix.dirname(fromFile), toFile).replace(/\.ts$/, '');
  return result.startsWith('.') ? result : `./${result}`;
}
function rewriteImports(file, text, mapper) {
  const ast = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
  const changes = [];
  for (const statement of ast.statements) {
    if ((!ts.isImportDeclaration(statement) && !ts.isExportDeclaration(statement)) || !statement.moduleSpecifier) continue;
    const node = statement.moduleSpecifier;
    assert(ts.isStringLiteral(node));
    const next = mapper(node.text);
    if (next !== node.text) changes.push({ start: node.getStart(ast) + 1, end: node.end - 1, text: next });
  }
  for (const change of changes.reverse()) text = text.slice(0, change.start) + change.text + text.slice(change.end);
  return text;
}
function replaceOnce(text, before, after) {
  assert.equal(text.split(before).length - 1, 1, `Source adaptation changed: ${before}`);
  return text.replace(before, after);
}
