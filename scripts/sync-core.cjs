const inputs = new Map();
function visit(file) {
  if (inputs.has(file)) return;
  assert(sourceFiles.has(file), `Missing source: ${file}`);
  const text = source(file);
  inputs.set(file, text);
  for (const dependency of ts.preProcessFile(text).importedFiles) {
    const specifier = dependency.fileName;
    if (!specifier.startsWith('.')) {
      assert(aliases.has(specifier), `Unsupported dependency: ${specifier}`);
      continue;
    }
    const base = path.posix.normalize(path.posix.join(path.posix.dirname(file), specifier));
    const resolved = [base, `${base}.ts`, `${base}/index.ts`].find((item) => sourceFiles.has(item));
    assert(resolved && resolved.startsWith('src/'), `External source dependency: ${specifier}`);
    visit(resolved);
  }
}
